    "      '.usermenu__info-type, [class*=\"account-type\"], [class*=\"usermenu__info\"], [class*=\"account-info\"]'",
    '    );',
    '',
    '    potentialAccountTypes.forEach(function(el) {',
    "      if (/demo/i.test(el.textContent || '')) {",
    '        el.textContent = liveText;',
    '        el.style.color = liveColor;',
    "        el.style.fontWeight = 'bold';",
    "        el.classList.remove('is-demo', 'usermenu__info-type--demo');",
    "        el.classList.add('qx-live-text-active');",
    '      }',
    '    });',
    '',
    '    var potentialBalances = document.querySelectorAll(',
    "      '.usermenu__info-balance, [class*=\"usermenu__info-balance\"], [class*=\"balance-val\"], [class*=\"balance_value\"], .header__balance'",
    '    );',
    '',
    '    potentialBalances.forEach(function(el) {',
    '      el.textContent = liveBalance;',
    "      el.style.fontWeight = 'bold';",
    '    });',
    '',
    '    // Tree walker for any un-classed Demo texts in top navigation',
    '    var walker = document.createTreeWalker(',
    '      document.body,',
    '      NodeFilter.SHOW_TEXT,',
    '      {',
    '        acceptNode: function(node) {',
    '          var parent = node.parentElement;',
    '          if (!parent) return NodeFilter.FILTER_REJECT;',
    '          var tag = parent.tagName.toLowerCase();',
    "          if (tag === 'script' || tag === 'style' || tag === 'textarea' || parent.id === '__qx_hud_root__') {",
    '            return NodeFilter.FILTER_REJECT;',
    '          }',
    "          var text = node.nodeValue || '';",
    "          if (/^\\s*demo(\\s+account)?\\s*$/i.test(text) || text.trim() === 'ডেমো' || text.trim() === 'ডেমো একাউন্ট') {",
