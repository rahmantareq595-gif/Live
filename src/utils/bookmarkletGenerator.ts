    "      '    <label style=\"display:block;margin-bottom:4px;color:#9ca3af;font-size:11px;\">Leaderboard Profit</label>',",
    "      '    <input id=\"__qx_in_profit__\" type=\"text\" value=\"' + (CONFIG.leaderboard ? CONFIG.leaderboard.profit : '') + '\" style=\"width:100%;background:#1f2937;border:1px solid #374151;color:#00e676;padding:6px 10px;border-radius:6px;margin-bottom:12px;font-size:13px;box-sizing:border-box;\" />',",
    "      '    <button id=\"__qx_btn_apply__\" style=\"width:100%;background:#00e676;color:#000;font-weight:700;border:none;padding:8px;border-radius:6px;cursor:pointer;font-size:12px;\">Apply Updates</button>',",
    "      '  </div>',",
    "      '</div>'",
    "    ].join('\\n');",
    '    document.body.appendChild(hud);',
