    '// @name         Quotex Live Account Pro & Watermark Remover',
    '// @namespace    https://quotex-studio.app/',
    '// @version      2.5.0',
    '// @description  Converts Quotex Demo to Live visually, with green text, live emoji, URL cloaker (/en/trade), leaderboard editor, and demo watermark removal.',
    '// @author       Quotex Studio',
    '// @match        *://*.quotex.io/*',
    '// @match        *://*.quotex-broker.com/*',
    '// @match        *://*.qxbroker.com/*',
    '// @match        *://*.qxbroker.io/*',
    '// @match        *://*.quotex.com/*',
