    '    while ((currentNode = walker.nextNode())) {',
    '      currentNode.nodeValue = liveText;',
    '      if (currentNode.parentElement) {',
    '        currentNode.parentElement.style.color = liveColor;',
    "        currentNode.parentElement.style.fontWeight = 'bold';",
    '      }',
    '    }',
    '  }',
    '',
    '  // 4. Leaderboard Injector / Customizer',
    '  function customizeLeaderboard() {',
    '    if (!CONFIG.leaderboard || !CONFIG.leaderboard.enabled) return;',
    '',
    '    var leaderboardContainers = document.querySelectorAll(',
    "      '[class*=\"leaderboard\"], [class*=\"top-traders\"], [class*=\"sidebar__section-leaderboard\"], .modal-leaderboard'",
    '    );',
    '',
    '    if (leaderboardContainers.length === 0) return;',
    '',
    '    var rank = CONFIG.leaderboard.rank || 1;',
    "    var name = CONFIG.leaderboard.name || 'Tareq Rahman';",
    "    var flag = CONFIG.leaderboard.countryFlag || '🇧🇩';",
    "    var profit = CONFIG.leaderboard.profit || '+$5,480.20';",
    '',
    '    leaderboardContainers.forEach(function(container) {',
    "      var rows = container.querySelectorAll('[class*=\"row\"], [class*=\"item\"], [class*=\"trader-card\"], tr');",
    '      if (rows.length > 0) {',
    '        var targetRowIndex = Math.min(Math.max(0, rank - 1), rows.length - 1);',
    '        var targetRow = rows[targetRowIndex];',
    "        if (targetRow && !targetRow.getAttribute('data-qx-customized')) {",
    "          targetRow.setAttribute('data-qx-customized', 'true');",
    "          targetRow.style.background = 'rgba(0, 230, 118, 0.08)';",
    "          targetRow.style.border = '1px solid rgba(0, 230, 118, 0.3)';",
    "          targetRow.style.borderRadius = '6px';",
    '',
    "          var nameEl = targetRow.querySelector('[class*=\"name\"], [class*=\"nickname\"], [class*=\"user\"]');",
    '          if (nameEl) nameEl.textContent = flag + " " + name;',
    '',
    "          var profitEl = targetRow.querySelector('[class*=\"profit\"], [class*=\"sum\"], [class*=\"amount\"]');",
    '          if (profitEl) {',
    '            profitEl.textContent = profit;',
    "            profitEl.style.color = '#00e676';",
    "            profitEl.style.fontWeight = 'bold';",
    '          }',
    '',
    "          var rankEl = targetRow.querySelector('[class*=\"rank\"], [class*=\"place\"], [class*=\"number\"]');",
    '          if (rankEl) rankEl.textContent = "#" + rank;',
    '        }',
    '      }',
    '    });',
    '  }',
    '',
    '  function updateAll() {',
    '    cloakUrlAndTitle();',
    '    purgeDemoWatermarks();',
    '    transformAccountHeader();',
    '    customizeLeaderboard();',
    '  }',
    '  window.__QX_UPDATE_ALL__ = updateAll;',
    '  updateAll();',
    '',
    '  // 5. Continuous MutationObserver',
    '  if (CONFIG.continuousSync && !window.__QX_OBSERVER__) {',
    '    var debounceTimer;',
    '    window.__QX_OBSERVER__ = new MutationObserver(function() {',
    '      clearTimeout(debounceTimer);',
    '      debounceTimer = setTimeout(updateAll, 60);',
    '    });',
    '    window.__QX_OBSERVER__.observe(document.body, {',
    '      childList: true,',
    '      subtree: true,',
    '      characterData: true',
    '    });',
    '  }',
    '',
    '  // 6. Floating On-Screen Quick Control HUD (F2 to toggle)',
    "  if (CONFIG.enableHUD && !document.getElementById('__qx_hud_root__')) {",
    "    var hud = document.createElement('div');",
    "    hud.id = '__qx_hud_root__';",
